"""Prepare immutable original-image/record evidence; never performs inference.

One canonical occurrence is selected per encoded-image SHA. Original TAR
annotations are actually read and checked against the native index component
hashes. Other occurrences are explicitly outside this bounded evidence scope.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
import csv
import hashlib
import io
import json
import os
from pathlib import Path
import re
import struct
import time

import pyarrow.compute as pc
import pyarrow.parquet as pq
from PIL import Image, ImageOps

SCHEMA = 'corpus.source_grounded_review_inputs.v1'
ANNOTATIONS = {'conversations.txt', 'data_type.txt', 'ds_name.txt', 'orig_url.txt', 'mdp.txt', 'ntok.txt'}
REQUIRED = {'conversations.txt', 'data_type.txt', 'ds_name.txt', 'orig_url.txt'}
CLUES = re.compile(r'AI[- ]generated|artificial intelligence|stable.?diffusion|midjourney|dall[ -]?e|text.to.image|generated by|synthetic|rendered|photoshop|firefly', re.I)


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False)


def digest(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(8 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def bound(path, expected=None):
    path = Path(path).resolve(strict=True)
    value = {'path': str(path), 'sha256': sha(path), 'size_bytes': path.stat().st_size}
    if expected is not None and value['sha256'] != expected:
        raise ValueError('Source hash mismatch: ' + str(path))
    return value


def load(path):
    return json.loads(Path(path).read_text())


def atomic(path, value):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    raw = (canonical(value) + '\n').encode()
    if path.exists():
        if path.read_bytes() != raw:
            raise ValueError('Immutable input changed: ' + str(path))
        return
    temporary = path.with_name(path.name + f'.tmp.{os.getpid()}')
    with temporary.open('wb') as stream:
        stream.write(raw); stream.flush(); os.fsync(stream.fileno())
    os.replace(temporary, path)


def progress(path, value):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(canonical(value) + '\n'); os.replace(temporary, path)


def nested(value):
    for _ in range(4):
        if not isinstance(value, str):
            return value
        try:
            value = json.loads(value)
        except json.JSONDecodeError:
            value = json.loads(value.replace('\\"', '"'))
    raise ValueError('Excessively nested reference')


def inventory(run, output):
    manifest_path = run/'operations/human_review_inventory_20261029/MANIFEST.json'
    original = load(manifest_path)
    selection = {}
    for item in original['files']:
        bound(item['path'], item['sha256'])
        with Path(item['path']).open(encoding='utf-8-sig', newline='') as stream:
            rows = list(csv.DictReader(stream))
        if len(rows) != item['rows']:
            raise ValueError('Inventory row count mismatch')
        for row in rows:
            aid = row['asset_id']
            if aid in selection or not re.fullmatch('[0-9a-f]{64}', aid):
                raise ValueError('Duplicate/invalid asset ID')
            selection[aid] = row
    if len(selection) != 28516 or len(selection) != original['total_review_candidates']:
        raise ValueError('Unexpected review scope')
    source = bound(original['source']['path'], original['source']['sha256'])
    catalog_path = run/'native/catalog.json'
    native_catalog = load(catalog_path)
    native_manifest = load(run/'native/COMPLETE.json')
    bound(catalog_path, native_manifest['catalog_sha256'])
    sources = {'inventory_manifest': bound(manifest_path), 'screening': source,
               'screening_complete': bound(run/'screening/COMPLETE.json'),
               'csv_files': [bound(x['path'], x['sha256']) for x in original['files']],
               'native_complete': bound(run/'native/COMPLETE.json'),
               'native_catalog': bound(catalog_path), 'reconciliation_complete': bound(run/'reconciliation/COMPLETE.json'),
               'source_roots': bound(run/'source_roots.json'), 'preparer': bound(__file__)}
    seeds = []
    for number in range(256):
        prefix = f'{number:02x}'; ids = {a for a in selection if a.startswith(prefix)}
        receipt_path = run/'reconciliation/buckets'/prefix/'COMPLETE.json'
        receipt = load(receipt_path)
        item = next(x for x in receipt['artifacts'] if Path(x['path']).name == 'api_review.parquet')
        path = run/'reconciliation'/item['path']; source_binding = bound(path, item['sha256'])
        table = pq.read_table(path)
        table = table.filter(pc.is_in(table['asset_id'], value_set=__import__('pyarrow').array(sorted(ids))))
        selected_rows = [(row, source_binding) for row in table.to_pylist()]
        missing = ids - {row['asset_id'] for row, _ in selected_rows}
        if missing:
            # A quality-pending row can be outside the detector API candidates.
            item = next(x for x in receipt['artifacts'] if Path(x['path']).name == 'assets.parquet')
            path = run/'reconciliation'/item['path']; fallback_binding = bound(path, item['sha256'])
            fallback = pq.read_table(path)
            fallback = fallback.filter(pc.is_in(fallback['asset_id'], value_set=__import__('pyarrow').array(sorted(missing))))
            selected_rows.extend((row, fallback_binding) for row in fallback.to_pylist())
        for row, row_binding in selected_rows:
            aid = row['asset_id']; ref = nested(row['original_ref_json'])
            if ref.get('sha256') != aid or ref.get('kind') != 'tar':
                raise ValueError('Canonical image reference does not bind selected asset')
            seeds.append({'item_id': aid, 'ref': ref, 'occurrence_count': row['occurrence_count'],
                          'source_count': row['source_count'], 'source': row['source'],
                          'sample_id': row['sample_id'], 'image_index': row['image_index'],
                          'prior_screening': selection[aid], 'reconciliation_binding': row_binding,
                          'reconciliation_receipt': bound(receipt_path)})
    if {x['item_id'] for x in seeds} != set(selection) or len(seeds) != len(selection):
        raise ValueError('Reconciliation does not cover exact CSV selection')
    catalog = {x['source_shard']: x for x in native_catalog}
    return sorted(seeds, key=lambda x: x['item_id']), catalog, sources


def clip(text, limit, focus=0):
    if len(text) <= limit:
        return {'text': text, 'original_characters': len(text), 'start_character': 0, 'end_character': len(text), 'truncated': False}
    start = max(0, min(focus - limit//3, len(text)-limit))
    return {'text': text[start:start+limit], 'original_characters': len(text), 'start_character': start,
            'end_character': start+limit, 'truncated': True}


def read_component(stream, component):
    offset, size = component['offset_data'], component['size']
    if type(offset) is not int or type(size) is not int or size < 0:
        raise ValueError('Invalid component bounds')
    stream.seek(offset); raw = stream.read(size)
    if len(raw) != size or hashlib.sha256(raw).hexdigest() != component['sha256']:
        raise ValueError('Original component bytes changed: ' + component['member'])
    return raw


def prepare_one(seed, native, native_binding, archive, output):
    aid = seed['item_id']; ref = seed['ref']; key = ref['member'].split('.', 1)[0]
    locator = nested(native['original_locator_json'])
    if locator['path'] != ref['path'] or locator['source_key'] != key:
        raise ValueError('Native record locator differs from image reference')
    components = {x['member']: x for x in locator['components']}
    image_component = components[ref['member']]
    if image_component['sha256'] != aid or image_component['offset_data'] != ref['offset_data'] or image_component['size'] != ref['size']:
        raise ValueError('Native record image binding mismatch')
    before = archive.stat()
    if before.st_size != ref['archive_size'] or locator['archive_sha256'] != ref['archive_sha256']:
        raise ValueError('Archive size/binding mismatch')
    annotations = {}; annotation_bindings = []
    with archive.open('rb') as stream:
        image_raw = read_component(stream, image_component)
        for member, component in components.items():
            suffix = member[len(key)+1:]
            if suffix in ANNOTATIONS:
                raw = read_component(stream, component)
                annotations[suffix] = raw.decode('utf-8')
                annotation_bindings.append({**component, 'sha256_verified_from_original_bytes': True})
    after = archive.stat()
    if (before.st_size, before.st_mtime_ns, before.st_ctime_ns) != (after.st_size, after.st_mtime_ns, after.st_ctime_ns):
        raise ValueError('Archive changed while reading')
    if not REQUIRED <= annotations.keys():
        raise ValueError('Original required record metadata missing')
    if annotations['ds_name.txt'].strip() != seed['source']:
        raise ValueError('Original declared source mismatch')
    with Image.open(io.BytesIO(image_raw)) as image:
        image.load(); decoded_format = image.format; image = ImageOps.exif_transpose(image).convert('RGB')
        pixel_sha = hashlib.sha256(struct.pack('>II', *image.size) + image.tobytes()).hexdigest()
        dimensions = list(image.size)
    image_path = output/'images'/aid[:2]/(aid + Path(ref['member']).suffix.lower())
    image_path.parent.mkdir(parents=True, exist_ok=True)
    if image_path.exists():
        if sha(image_path) != aid:
            raise ValueError('Existing copied original image changed')
    else:
        temp = image_path.with_suffix(image_path.suffix+'.tmp')
        temp.write_bytes(image_raw); os.replace(temp, image_path)
    metadata = nested(native['adapter_metadata_json'])
    text = annotations['conversations.txt']
    placeholders = [match.start() for match in re.finditer(re.escape('<image>'), text)]
    image_index = int(ref['member'][len(key)+1:].split('.')[0])
    if image_index != seed['image_index'] or image_index >= native['image_count']:
        raise ValueError('Target image slot mismatch')
    mapping = metadata.get('pairing_state') == 'verified' and len(placeholders) == native['image_count']
    focus = placeholders[image_index] if mapping else 0
    target_turn = text[:focus].count('<EOCL>\n') if mapping else None
    conversation = clip(text, 17000, focus)
    full_record = {'schema': 'corpus.original_record_evidence.v1', 'item_id': aid,
                   'portable_archive': {k: ref[k] for k in ('dataset_id','path','archive_sha256','archive_size')},
                   'source_key': key, 'native_sample_id': seed['sample_id'], 'native_record_binding': native_binding,
                   'native_row': native, 'annotations': annotations, 'annotation_components': annotation_bindings,
                   'annotation_content_sha256': digest(annotations), 'raw_image_sha256': aid,
                   'archive_stat_at_read': {'size': before.st_size, 'mtime_ns': before.st_mtime_ns},
                   'verification': 'Each selected original TAR member was read and SHA checked against the SHA-verified native index; full TAR SHA was not recomputed.'}
    record_path = output/'records'/aid[:2]/(aid+'.json'); atomic(record_path, full_record)
    hints = []
    for name, value in annotations.items():
        for match in CLUES.finditer(value):
            hints.append({'field': name, 'match_start': match.start(), 'excerpt': value[max(0,match.start()-70):match.end()+110]})
            if len(hints) >= 8: break
        if len(hints) >= 8: break
    record = {'source_key': key, 'declared_dataset_source': annotations['ds_name.txt'].strip(),
              'data_type': annotations['data_type.txt'].strip(), 'target_image_member': ref['member'],
              'target_image_index_zero_based': image_index, 'record_image_count': native['image_count'],
              'placeholder_alignment_verified': mapping, 'target_turn_zero_based': target_turn,
              'caption_assignment': 'Single-image record: assistant text is task context, not guaranteed truthful provenance.' if native['image_count']==1 else
                 'Multi-image record: only the indexed image is attached; do not assign another image caption to it. Context may discuss several images.',
              'conversations': conversation, 'original_url_field': clip(annotations['orig_url.txt'], 3000),
              'other_original_metadata': {name: clip(value, 500) for name,value in annotations.items() if name not in REQUIRED},
              'generation_or_editing_text_matches': hints, 'annotation_content_sha256': full_record['annotation_content_sha256'],
              'full_record_evidence': bound(record_path),
              'metadata_is_untrusted_source_content': True, 'external_urls_fetched': False}
    if len(canonical(record)) > 24000:
        record['conversations'] = clip(text, 12000, focus)
        if len(canonical(record)) > 24000:
            raise ValueError('Bounded model source context exceeds 24000 characters')
    original_ref = {k:v for k,v in ref.items() if k not in {'metadata_json','exists'}}
    result = {'schema': SCHEMA, 'item_id': aid, 'image_path': str(image_path), 'image_sha256': aid,
              'image_pixel_sha256': pixel_sha, 'image_pixel_sha256_contract': 'SHA256(big-endian uint32 width,height + EXIF-transposed RGB bytes)',
              'original_image': {'sha256': aid, 'portable_ref': original_ref, 'bytes': len(image_raw),
                                 'decoded_dimensions': dimensions, 'decoder': 'Pillow', 'format': decoded_format, 'fully_decoded': True},
              'source_records': [record], 'prior_screening': seed['prior_screening'],
              'scope': {'total_occurrences': seed['occurrence_count'], 'total_declared_sources': seed['source_count'],
                        'selected_records': 1, 'selection': 'Existing deterministic canonical occurrence whose original image SHA matches item_id',
                        'unread_occurrences': max(0,seed['occurrence_count']-1),
                        'other_sources_not_inspected': max(0,seed['source_count']-1),
                        'multi_record_scope_limited': seed['occurrence_count']>1,
                        'text_truncated': any(value.get('truncated',False) for value in [record['conversations'],record['original_url_field'],*record['other_original_metadata'].values()]),
                        'full_text_preserved': True, 'model_context_character_limit': 24000,
                        'source_context_characters': len(canonical(record)), 'all_original_record_images_decoded': native['image_count']==1},
              'source_bindings': {'reconciliation_parquet': seed['reconciliation_binding'],
                                  'reconciliation_receipt': seed['reconciliation_receipt'], 'native_parquet': native_binding,
                                  'original_record_evidence': record['full_record_evidence']}}
    atomic(output/'items'/aid[:2]/(aid+'.json'), result)
    return result


def group(seeds, entry, roots, run, output):
    native_path = run/'native'/entry['path']; native_binding = bound(native_path, entry['sha256'])
    wanted = {seed['ref']['member'].split('.',1)[0] for seed in seeds}
    table = pq.read_table(native_path, columns=['source_key','image_count','adapter_metadata_json','original_locator_json'])
    table = table.filter(pc.is_in(table['source_key'], value_set=__import__('pyarrow').array(sorted(wanted))))
    records = {row['source_key']:row for row in table.to_pylist()}
    if set(records) != wanted:
        raise ValueError('Canonical record absent from native index')
    result = []
    for seed in seeds:
        existing = output/'items'/seed['item_id'][:2]/(seed['item_id']+'.json')
        if existing.exists():
            item = load(existing)
            bound(item['image_path'],item['image_sha256']);bound(item['source_records'][0]['full_record_evidence']['path'],item['source_records'][0]['full_record_evidence']['sha256'])
            result.append(item);continue
        ref=seed['ref']; source_root=Path(roots[ref['dataset_id']]).resolve()
        archive=(source_root/ref['path']).resolve(strict=True)
        if not archive.is_relative_to(source_root) or Path(ref['path']).is_absolute():
            raise ValueError('Portable archive escaped dataset root')
        result.append(prepare_one(seed, records[ref['member'].split('.',1)[0]], native_binding, archive, output))
    return result


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--run',type=Path,required=True);parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--canary',type=int,default=0);parser.add_argument('--workers',type=int,default=4)
    args=parser.parse_args();run=args.run.resolve();output=args.output.resolve();output.mkdir(parents=True,exist_ok=True)
    import fcntl
    with (output/'.prepare.lock').open('a') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        started=time.time();seeds,catalog,sources=inventory(run,output)
        if args.canary:
            # Deterministic source diversity; no visual assessment is invented.
            chosen=[];sources_seen=set()
            for seed in seeds:
                category=(seed['source'],seed['prior_screening']['review_category'])
                if category not in sources_seen:
                    chosen.append(seed);sources_seen.add(category)
                    if len(chosen)==args.canary:break
            seeds=chosen
        roots=load(run/'source_roots.json');groups=defaultdict(list)
        for seed in seeds:groups[seed['ref']['path']].append(seed)
        identity={'schema':SCHEMA,'sources':sources,'expected_items':len(seeds),'item_ids_sha256':digest(sorted(x['item_id'] for x in seeds)),
                  'selection_scope':'canary' if args.canary else 'full_28516','selected_records_per_asset':1,'model_context_character_limit':24000}
        prefix='canary' if args.canary else 'source'
        atomic(output/(prefix+'_IDENTITY.json'),identity)
        completed=[];errors=[]
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            tasks={pool.submit(group,rows,catalog[shard],roots,run,output):shard for shard,rows in groups.items()}
            for future in as_completed(tasks):
                try:completed.extend(future.result())
                except Exception as exc:errors.append({'archive':tasks[future],'error_type':type(exc).__name__,'error':str(exc)})
                progress(output/(prefix+'_PROGRESS.json'),{'phase':'preparing','completed_items':len(completed),'expected_items':len(seeds),
                         'failed_archives':len(errors),'elapsed_seconds':time.time()-started,'updated_at':time.time(),'pid':os.getpid()})
        if errors:
            progress(output/(prefix+'_ERRORS.json'),{'complete':False,'errors':errors});raise RuntimeError(f'{len(errors)} source archive groups failed')
        if len(completed)!=len(seeds) or {x['item_id'] for x in completed}!={x['item_id'] for x in seeds}:raise ValueError('Input coverage mismatch')
        target=output/(prefix+'_items.jsonl');temp=target.with_name(target.name+'.tmp')
        with temp.open('w') as stream:
            for item in sorted(completed,key=lambda x:x['item_id']):stream.write(canonical(item)+'\n')
            stream.flush();os.fsync(stream.fileno())
        os.replace(temp,target)
        manifest={'schema':SCHEMA,'complete':True,'inference_performed':False,'items':len(completed),
                  'source_items':bound(target),'identity':bound(output/(prefix+'_IDENTITY.json')),
                  'sources':sources,'by_prior_category':dict(Counter(x['prior_screening']['review_category'] for x in completed)),
                  'by_declared_source':dict(Counter(x['source_records'][0]['declared_dataset_source'] for x in completed)),
                  'truncated_contexts':sum(x['scope']['text_truncated'] for x in completed),
                  'limited_multi_record_scope':sum(x['scope']['multi_record_scope_limited'] for x in completed),
                  'unverified_placeholder_alignments':sum(not x['source_records'][0]['placeholder_alignment_verified'] for x in completed),
                  'original_sources_modified':False,'external_urls_fetched':False,'elapsed_seconds':time.time()-started}
        progress(output/(prefix+'_MANIFEST.json'),manifest)
        progress(output/(prefix+'_PROGRESS.json'),{'phase':'complete','completed_items':len(completed),'expected_items':len(seeds),'updated_at':time.time(),'pid':os.getpid()})
        print(canonical(manifest))


if __name__=='__main__':main()

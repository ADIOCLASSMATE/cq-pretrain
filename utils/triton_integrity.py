"""Check the pinned Triton-Ascend payload without importing Torch or Triton.

Ascend owns the active triton/ package. Its RECORD is authoritative even
when a community distribution is also installed. Generated bytecode is ignored.
This detects accidental overwrite/deletion, not tampering with RECORD itself.
"""

import argparse
import base64
import csv
import hashlib
from importlib import metadata
from importlib.machinery import PathFinder
import io
import json
from pathlib import Path, PurePosixPath
import sys


ROOT = Path(__file__).resolve().parents[1]
REPAIR = f"python3 {ROOT / 'scripts/setup_mindspeed.py'} --python"
REQUIRED_SHARED = {
    "triton/__init__.py",
    "triton/compiler/compiler.py",
    "triton/runtime/jit.py",
    "triton/_C/libtriton.so",
}
REQUIRED_ASCEND = {
    "triton/backends/ascend/__init__.py",
    "triton/backends/ascend/compiler.py",
    "triton/backends/ascend/driver.py",
}


def _payload(distribution):
    # Some importlib.metadata versions filter missing paths from .files.
    # Parse RECORD directly so a deleted non-entrypoint file cannot disappear
    # from the verification set.
    record = distribution.read_text("RECORD")
    if record is None:
        raise RuntimeError(f"{distribution.metadata['Name']}: installed RECORD is missing")
    payload = {}
    for row in csv.reader(io.StringIO(record)):
        if len(row) != 3:
            raise RuntimeError(f"Malformed {distribution.metadata['Name']} RECORD row: {row}")
        name, digest, size = row
        path = PurePosixPath(name)
        if not path.parts or path.parts[0] != "triton":
            continue
        if path.suffix == ".pyc" or "__pycache__" in path.parts:
            continue
        if path.is_absolute() or ".." in path.parts:
            raise RuntimeError(f"Invalid Triton RECORD path: {name}")
        if str(path) in payload:
            raise RuntimeError(f"Duplicate Triton RECORD path: {name}")
        payload[str(path)] = digest, size
    if not payload:
        raise RuntimeError(f"{distribution.metadata['Name']}: RECORD has no Triton payload")
    return payload


def verify_triton(lock=None):
    """Verify versions, import resolution and every Ascend-owned payload file."""
    if lock is None:
        lock = json.loads((ROOT / "configs/deps.core17.lock.json").read_text())
    pinned = lock["gdn_runtime"]
    expected_versions = {
        "triton-ascend": pinned["triton_ascend"]["version"],
    }
    distributions = {}
    for name, version in expected_versions.items():
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError as error:
            raise RuntimeError(f"Required distribution is missing: {name}=={version}") from error
        if dist.version != version:
            raise RuntimeError(f"{name}: expected {version}, installed {dist.version}")
        distributions[name] = dist
    ascend = distributions["triton-ascend"]
    ascend_files = _payload(ascend)
    missing = (REQUIRED_SHARED | REQUIRED_ASCEND) - set(ascend_files)
    if missing:
        raise RuntimeError(f"Triton RECORD is incomplete: missing required entries {sorted(missing)}")

    # PathFinder locates the import without executing the package initializer.
    expected_init = Path(ascend.locate_file("triton/__init__.py")).resolve()
    spec = PathFinder.find_spec("triton", sys.path)
    if spec is None or spec.origin is None or Path(spec.origin).resolve() != expected_init:
        raise RuntimeError(
            f"Triton import is shadowed: expected {expected_init}, "
            f"found {getattr(spec, 'origin', None)}. Check PYTHONPATH for an overriding package."
        )

    checked_bytes = 0
    for name, (expected_digest, recorded_size) in sorted(ascend_files.items()):
        path = Path(ascend.locate_file(name))
        if not expected_digest.startswith("sha256=") or not recorded_size:
            raise RuntimeError(f"Triton-Ascend RECORD lacks SHA-256/size for {name}")
        expected_size = int(recorded_size)
        if not path.is_file():
            raise RuntimeError(f"Triton-Ascend file is missing: {path}")
        size = path.stat().st_size
        if size != expected_size:
            raise RuntimeError(f"Triton-Ascend size mismatch: {path} (expected {expected_size}, got {size})")
        with path.open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").digest()
        actual = base64.urlsafe_b64encode(digest).rstrip(b"=").decode("ascii")
        if actual != expected_digest.removeprefix("sha256="):
            raise RuntimeError(f"Triton-Ascend SHA-256 mismatch: {path}")
        checked_bytes += size
    return {
        "versions": expected_versions,
        "checked_files": len(ascend_files),
        "core_files": len(REQUIRED_SHARED),
        "checked_bytes": checked_bytes,
        "import_path": str(expected_init),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quiet", action="store_true", help="Only print failures")
    args = parser.parse_args(argv)
    try:
        result = verify_triton()
    except (RuntimeError, OSError, ValueError) as error:
        print(f"Triton integrity check failed: {error}\nRepair with: {REPAIR}", file=sys.stderr)
        return 1
    if not args.quiet:
        print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
